#!/usr/bin/env node
/**
 * Regenerates src/i18n/messages.ts from the files in src/i18n/locales/<locale>/<namespace>.json.
 *
 *   npm run i18n:index        (from apps/mobile)
 *
 * Metro only bundles files reached by static imports, so every message file
 * must be imported by name. Run this after adding a namespace (or when a merge
 * conflicts in messages.ts — never hand-merge it, just regenerate).
 * `src/i18n/locales.test.ts` fails when messages.ts and the folder disagree.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const LOCALES = ['en', 'es', 'fr', 'de', 'ar', 'ur'];
const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'i18n');
const localesDir = join(root, 'locales');

const namespaces = readdirSync(join(localesDir, 'en'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.slice(0, -'.json'.length))
  .sort();

const ident = (locale, ns) => `${locale}_${ns.replace(/[^A-Za-z0-9]/g, '_')}`;

const lines = [
  '// AUTO-GENERATED by scripts/gen-i18n-index.mjs — do not edit by hand.',
  '// Run `npm run i18n:index` in apps/mobile after adding a namespace file.',
  '',
];
for (const ns of namespaces) {
  for (const locale of LOCALES) {
    lines.push(`import ${ident(locale, ns)} from './locales/${locale}/${ns}.json';`);
  }
}
lines.push('', 'export const MESSAGES = {');
for (const locale of LOCALES) {
  lines.push(`  ${locale}: {`);
  for (const ns of namespaces) lines.push(`    ${JSON.stringify(ns)}: ${ident(locale, ns)},`);
  lines.push('  },');
}
lines.push('} as const;', '', 'export type Namespace = keyof (typeof MESSAGES)[\'en\'];', '');
lines.push(`export const NAMESPACES = Object.keys(MESSAGES.en) as Namespace[];`, '');

writeFileSync(join(root, 'messages.ts'), lines.join('\n'));
console.log(`messages.ts: ${namespaces.length} namespaces × ${LOCALES.length} locales`);
